package main

import "fmt"

// pra05: Go の演算子ごとの動作確認。
//
// 実行結果（上から順に）:
//   sum    2 + 3   = 5
//   des    2 - 5   = -3
//   times  2 * 4   = 8
//   per    6 / 2   = 3
//   ext    5 % 2   = 1
//   and    4 & 2   = 0
//   or     2 | 6   = 6
//   xor    3 ^ 6   = 5
//   AndNot 3 &^ 6  = 1
//   left   5 << 4  = 80
//   right  4 >> 2  = 1

func main() {
	// --- 算術演算子 ---
	sum()   // +  加算
	des()   // -  減算
	times() // *  乗算
	per()   // /  除算（整数どうしは切り捨て）
	ext()   // %  剰余（余り）

	// --- ビット演算子（2進数で1桁ずつ処理する） ---
	and()    // &   AND     : 両方1なら1
	or()     // |   OR      : どちらか1なら1
	xor()    // ^   XOR     : 違えば1、同じなら0
	AndNot() // &^  AND NOT : 右が1のビットを左から消す（bit clear）

	// --- シフト演算子 ---
	left()  // << 左シフト : ビットを左へ動かす = 2のn乗を掛ける
	right() // >> 右シフト : ビットを右へ動かす = 2のn乗で割る（切り捨て）
}

// ======== 算術演算子 ========

func sum() {
	i := 2
	j := 3
	// 2 + 3 = 5。ふつうの足し算。
	fmt.Println(i + j) // 5
}

func des() {
	i := 5
	j := 2
	// 引く順番に注意: ここは j - i なので 2 - 5 = -3。
	// int は符号ありなので負の数もそのまま表せる。
	fmt.Println(j - i) // -3
}

func times() {
	i := 2
	j := 4
	// 2 * 4 = 8。
	fmt.Println(i * j) // 8
}

func per() {
	i := 6
	j := 2
	// 整数どうしの / は「整数除算」= 小数点以下を切り捨てる。
	// 6 / 2 = 3（ちょうど割り切れる）。
	// 例: 7 / 2 なら 3 になる（3.5 ではない）。小数が欲しければ float64 に変換する。
	fmt.Println(i / j) // 3
}

func ext() {
	i := 5
	j := 2
	// % は「割った余り」。5 ÷ 2 = 2 あまり 1 → 1。
	// / と % はセット: i == (i/j)*j + (i%j)
	fmt.Println(i % j) // 1
}

// ======== ビット演算子 ========
// ポイント: 数を2進数にして、同じ位置のビットどうしを比べる。
// 3ビットで書くと十分（今回の値は 0〜7）。

func and() {
	i := 4 // 100
	j := 2 // 010
	// & は「両方のビットが1のときだけ1」。
	//   100
	// & 010
	// -----
	//   000  → 0
	// 4 と 2 は立っているビットが重ならないので 0。
	fmt.Println(i & j) // 0
}

func or() {
	i := 2 // 010
	j := 6 // 110
	// | は「どちらかのビットが1なら1」。
	//   010
	// | 110
	// -----
	//   110  → 6
	fmt.Println(i | j) // 6
}

func xor() {
	i := 3 // 011
	j := 6 // 110
	// ^ は「ビットが違えば1、同じなら0」（排他的論理和）。
	//   011
	// ^ 110
	// -----
	//   101  → 5
	// 最下位: 1と0で違う→1 / 真ん中: 1と1で同じ→0 / 最上位: 0と1で違う→1
	fmt.Println(i ^ j) // 5
}

func AndNot() {
	i := 3 // 011
	j := 6 // 110
	// &^ は「右(j)のビットが1になっている桁を、左(i)から消す」。
	// j = 110 なので、上位2桁を i から消す:
	//   i    = 011
	//   消す桁 = ↑↑    (真ん中と最上位)
	//   結果  = 001  → 1
	// 「i &^ j」= 「i & (^j)」と同じ。使い道: フラグを下ろす処理。
	fmt.Println(i &^ j) // 1
}

// ======== シフト演算子 ========

func left() {
	i := 5 // 101
	j := 4
	// i << j : ビット列を左へ j 個ずらし、空いた右側は 0 で埋める。
	// 左に1つずらす = 2倍。j 個ずらす = 2^j 倍。
	//   101      (5)
	//   1010000  (左に4つ = 5 * 2^4 = 5 * 16 = 80)
	fmt.Println(i << j) // 80
}

func right() {
	i := 4 // 100
	j := 2
	// i >> j : ビット列を右へ j 個ずらす。はみ出た右側は捨てる。
	// 右に1つずらす = 2で割る（切り捨て）。j 個で 2^j で割る。
	//   100  (4)
	//   001  (右に2つ = 4 / 2^2 = 4 / 4 = 1)
	fmt.Println(i >> j) // 1
}
